const sqlService = require('../services/sql.service');
const logger = require('../utils/logger');

exports.getLeaveCategories = async (req, res) => {
    try {
        const leaveCategories = await sqlService.executeQuery(
            'SELECT',
            'leave_categories',
            {
                columns: [
                    'id',
                    'name',
                    'status',
                    'description',
                    'is_auto_generated',
                    'max_consecutive_days_allowed',
                    'min_notice_period_days',
                    'is_document_required',
                    'document_required_after_days'
                ],
                camelCase: true,
                booleanFields: ['is_auto_generated' , 'is_document_required']
            },
            {
                controller: 'leave',
                function: 'getLeaveCategories'
            }
        );

        return res.status(200).json({
            success: true,
            data: {
                leave_categories : leaveCategories
            }
            
        });

    } catch (err) {
        logger.logError(`[Controller Error] leave → getLeaveCategories: ${err.stack || err}`);

        return res.status(500).json({
            success: false,
            message: 'Failed to fetch leave categories.',
            error: err.message || 'Unknown error'
        });
    }
};

exports.addLeaveCategory = async (req, res) => {
    try {
        const {
            name,
            status = 0,
            description = null,
            isAutoGenerated = false,
            maxConsecutiveDaysAllowed = null,
            minNoticePeriodDays = 0,
            isDocumentRequired = false,
            documentRequiredAfterDays = null
        } = req.body;

        if (!name || typeof name !== 'string') {
            return res.status(400).json({
                success: false,
                message: 'Leave category name is required and must be a string.'
            });
        }

        // ✅ Check for duplicates
        const existing = await sqlService.executeQuery(
            'SELECT',
            'leave_categories',
            {
                columns: ['id'],
                where: { name },
                camelCase: true
            },
            { controller: 'leave', function: 'checkDuplicateLeaveCategory' }
        );

        if (existing.length > 0) {
            return res.status(409).json({
                success: false,
                message: `Leave category "${name}" already exists.`
            });
        }

        // ✅ Proceed with insert
        const result = await sqlService.executeQuery(
            'INSERT',
            'leave_categories',
            {
                columns: [
                    'name',
                    'status',
                    'description',
                    'is_auto_generated',
                    'max_consecutive_days_allowed',
                    'min_notice_period_days',
                    'is_document_required',
                    'document_required_after_days'
                ],
                values: [
                    name,
                    status,
                    description,
                    isAutoGenerated,
                    maxConsecutiveDaysAllowed,
                    minNoticePeriodDays,
                    isDocumentRequired,
                    documentRequiredAfterDays
                ]
            },
            { controller: 'leave', function: 'addLeaveCategory' }
        );

        return res.status(201).json({
            success: true,
            message: 'Leave category added successfully.',
            data: result
        });
    } catch (error) {
        logger.logError(error);
        return res.status(500).json({
            success: false,
            message: 'Failed to add leave category',
            error: error.message
        });
    }
};

exports.editLeaveCategory = async (req, res) => {
    try {
        const id = parseInt(req.body.id, 10);
        if (!id) {
            return res.status(400).json({
                success: false,
                message: 'Invalid leave category ID'
            });
        }

        const {
            name,
            status,
            description,
            isAutoGenerated,
            maxConsecutiveDaysAllowed,
            minNoticePeriodDays,
            isDocumentRequired,
            documentRequiredAfterDays
        } = req.body;

        const updateData = {};

        if (name !== undefined) updateData.name = name;
        if (status !== undefined) updateData.status = status;
        if (description !== undefined) updateData.description = description;
        if (isAutoGenerated !== undefined) updateData.is_auto_generated = isAutoGenerated;
        if (maxConsecutiveDaysAllowed !== undefined) updateData.max_consecutive_days_allowed = maxConsecutiveDaysAllowed;
        if (minNoticePeriodDays !== undefined) updateData.min_notice_period_days = minNoticePeriodDays;
        if (isDocumentRequired !== undefined) updateData.is_document_required = isDocumentRequired;
        if (documentRequiredAfterDays !== undefined) updateData.document_required_after_days = documentRequiredAfterDays;

        if (Object.keys(updateData).length === 0) {
            return res.status(400).json({
                success: false,
                message: 'No data provided for update'
            });
        }

        const result = await sqlService.executeQuery(
            'UPDATE',
            'leave_categories',
            {
                data: updateData,
                where: { id }
            },
            { controller: 'leave', function: 'editLeaveCategory' }
        );

        return res.status(200).json({
            success: true,
            message: 'Leave category updated successfully',
            data: result
        });
    } catch (error) {
        logger.logError(error);
        return res.status(500).json({
            success: false,
            message: 'Failed to update leave category',
            error: error.message
        });
    }
};

